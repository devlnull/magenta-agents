"""Codex CLI adapter: custom agents (TOML), skills in ~/.agents/skills, and a short AGENTS.md block.

Use in Codex: `$magenta <task>`. The conductor skill asks Codex to spawn the custom agents.
Codex does not run the Magenta guard, so each agent gets its write and shell rules as text.
Codex sandbox and approval settings of the session still apply.
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

import agents_md
import claude_code
import source
from source import MARKER, USER_NAMING, SourceError

EFFORT = {"low": "low", "medium": "medium", "high": "high", "xhigh": "high", "max": "high"}


def toml_multiline(text: str) -> str:
    if "'''" not in text:
        return "'''\n" + text + "'''"
    escaped = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return '"""\n' + escaped + '"""'


def agent_toml(root: Path, cfg: dict, agents: dict, agent_id: str) -> str:
    agent = agents[agent_id]
    mg = agent["meta"]["magenta"]
    profile = cfg["profiles"].get(mg["model_profile"]) or {}
    lines = [f"# {MARKER} from agents/{agent_id}.md. Do not edit this file.",
             f"name = {json.dumps(USER_NAMING.ref(agent_id))}",
             f"description = {json.dumps(source.description(agent))}"]
    model = profile.get("codex")
    if model and "<" not in str(model):
        lines.append(f"model = {json.dumps(model)}")
    if profile.get("effort") in EFFORT:
        lines.append(f"model_reasoning_effort = {json.dumps(EFFORT[profile['effort']])}")
    instructions = source.write_rules(agent) + source.instructions(root, cfg, agents, agent_id, USER_NAMING)
    lines.append("developer_instructions = " + toml_multiline(instructions))
    return "\n".join(lines) + "\n"


def agents_md_block(agents: dict) -> str:
    lines = [agents_md.BEGIN, f"<!-- {MARKER}. Do not edit this block. -->", "", "# Magenta agents", "",
             "To run a software task with the Magenta team, use the skill `$magenta` followed by the task.",
             "The skill selects the agents, runs them, and checks the result against the rules of all agents.", "",
             "Custom agents:", ""]
    lines += [f"- `{USER_NAMING.ref(a)}`: {agents[a]['meta']['magenta']['title']}" for a in agents]
    lines += ["", "Codex does not run the Magenta guard. Each agent follows its write rules by instruction.", "",
              agents_md.END]
    return "\n".join(lines) + "\n"


def build(root: Path, out: Path) -> dict:
    cfg = source.load_config(root)
    agents = source.load_agents(root, cfg.get("agents_enabled") or [])
    if out.exists():
        shutil.rmtree(out)
    (out / "agents").mkdir(parents=True)
    for agent_id in agents:
        (out / "agents" / f"{USER_NAMING.file(agent_id)}.toml").write_text(
            agent_toml(root, cfg, agents, agent_id), encoding="utf-8")
    skills = claude_code.write_skills(root, cfg, USER_NAMING, out / "skills")
    (out / "AGENTS.md").write_text(agents_md_block(agents), encoding="utf-8")
    return {"agents": sorted(agents), "skills": sorted(skills)}


def install(dist: Path, home: Path, force: bool = False) -> list[str]:
    if not (dist / "agents").exists():
        raise SourceError("dist/codex does not exist. Run: python3 magenta.py build")
    plan = [(p, home / ".codex" / "agents" / p.name) for p in sorted((dist / "agents").glob("*.toml"))]
    plan += [(p, home / ".agents" / "skills" / p.name) for p in sorted((dist / "skills").iterdir())]
    installed = claude_code._copy_plan(plan, home / ".codex" / "magenta", None, force)
    target = home / ".codex" / "AGENTS.md"
    current = target.read_text(encoding="utf-8") if target.exists() else ""
    target.write_text(agents_md.merge_block(current, (dist / "AGENTS.md").read_text(encoding="utf-8")),
                      encoding="utf-8")
    return installed + [f"{target} (Magenta block)"]


def uninstall(home: Path) -> None:
    agents_md.uninstall_codex(home)
