"""Gemini CLI adapter: subagents in ~/.gemini/agents, the /magenta command, and skills in ~/.agents/skills.

Use in Gemini CLI: `/magenta <task>`. Gemini subagents cannot call other subagents, so the conductor
starts all agents. Gemini CLI does not run the Magenta guard, so each agent gets its rules as text.
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

import claude_code
import source
from source import MARKER, USER_NAMING, SourceError

COMMAND = f'''# {MARKER}. Do not edit this file.
description = "Magenta: run a software task with the Magenta agent team (bug, performance, refactor, review, feature, and more)"
prompt = """
Activate the skill `magenta` and follow it for this request:

{{{{args}}}}
"""
'''


def agent_file(root: Path, cfg: dict, agents: dict, agent_id: str) -> str:
    agent = agents[agent_id]
    mg = agent["meta"]["magenta"]
    profile = cfg["profiles"].get(mg["model_profile"]) or {}
    fm = ["---", f"name: {USER_NAMING.ref(agent_id)}", f"description: {source.yaml_str(source.description(agent))}",
          "kind: local", f"max_turns: {int(mg.get('max_turns') or cfg.get('default_max_turns') or 60)}",
          f"timeout_mins: {30 if mg.get('role_type') == 'maker' else 15}"]
    model = profile.get("gemini")
    if model and "<" not in str(model):
        fm.append(f"model: {model}")
    fm.append("---")
    return "\n".join(fm) + "\n" + source.write_rules(agent) + source.instructions(root, cfg, agents, agent_id, USER_NAMING)


def build(root: Path, out: Path) -> dict:
    cfg = source.load_config(root)
    agents = source.load_agents(root, cfg.get("agents_enabled") or [])
    if out.exists():
        shutil.rmtree(out)
    (out / "agents").mkdir(parents=True)
    (out / "commands").mkdir()
    for agent_id in agents:
        (out / "agents" / f"{USER_NAMING.file(agent_id)}.md").write_text(
            agent_file(root, cfg, agents, agent_id), encoding="utf-8")
    (out / "commands" / "magenta.toml").write_text(COMMAND, encoding="utf-8")
    skills = claude_code.write_skills(root, cfg, USER_NAMING, out / "skills")
    return {"agents": sorted(agents), "skills": sorted(skills)}


def install(dist: Path, home: Path, force: bool = False) -> list[str]:
    if not (dist / "agents").exists():
        raise SourceError("dist/gemini does not exist. Run: python3 magenta.py build")
    gemini = home / ".gemini"
    plan = [(p, gemini / "agents" / p.name) for p in sorted((dist / "agents").glob("*.md"))]
    plan.append((dist / "commands" / "magenta.toml", gemini / "commands" / "magenta.toml"))
    plan += [(p, home / ".agents" / "skills" / p.name) for p in sorted((dist / "skills").iterdir())]
    return claude_code._copy_plan(plan, gemini / "magenta", None, force)
