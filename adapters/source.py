class SourceError(Exception):
    pass


@dataclass(frozen=True)
class Naming:
    """How generated names look. ref() is how text refers to an agent or skill; file() is the file name."""
    ref_prefix: str = "magenta-"
    file_prefix: str = "magenta-"

    def ref(self, name: str) -> str:
        if name == CONDUCTOR:
            return CONDUCTOR
        return name if name.startswith(self.ref_prefix) else self.ref_prefix + name

    def file(self, name: str) -> str:
        if name == CONDUCTOR:
            return CONDUCTOR
        return name if (self.file_prefix and name.startswith(self.file_prefix)) else self.file_prefix + name


USER_NAMING = Naming("magenta-", "magenta-")
PLUGIN_NAMING = Naming("magenta:", "")


def load_config(root: Path) -> dict:
    team = parse_yaml((root / "magenta.yaml").read_text(encoding="utf-8")) or {}
    models = parse_yaml((root / "models.yaml").read_text(encoding="utf-8")) or {}
    team.setdefault("prefix", "magenta-")
    team["profiles"] = models.get("profiles") or {}
    team["engines"] = models.get("engines") or {}
    return team


def load_agents(root: Path, ids) -> dict:
    agents = {}
    for agent_id in ids:
        path = root / "agents" / f"{agent_id}.md"
        if not path.exists():
            raise SourceError(f"agents/{agent_id}.md does not exist")
        meta, body = split_front_matter(path.read_text(encoding="utf-8"))
        agents[agent_id] = {"meta": meta, "body": body, "path": path}
    return agents


def skill_names(root: Path) -> list[str]:
    return sorted(p.parent.name for p in (root / "skills").glob("*/SKILL.md"))


def all_names(root: Path, cfg: dict) -> set[str]:
    return (set(cfg.get("agents_enabled") or []) | set(cfg.get("agents_planned") or [])
            | set(skill_names(root)) | {f"magenta-{s}" for s in GENERATED_SKILLS})


def rewrite_names(text: str, names, naming: Naming) -> str:
    """Rewrite backtick references to agents and skills, for example `qa` -> `magenta-qa`."""
    def repl(match):
        name = match.group(1)
        base = name[len("magenta-"):] if name.startswith("magenta-") else name
        return f"`{naming.ref(base)}`"
    alternatives = sorted(names, key=len, reverse=True)
    if not alternatives:
        return text
    pattern = r"`(" + "|".join(re.escape(n) for n in alternatives) + r")`"
    return re.sub(pattern, repl, text)


def constitution(root: Path) -> str:
    parts = [p.read_text(encoding="utf-8").strip() for p in sorted((root / "rules").glob("*.md"))]
    org = root / "standards" / "organization.md"
    if org.exists() and org.read_text(encoding="utf-8").strip():
        parts.append(org.read_text(encoding="utf-8").strip())
    return "# Magenta constitution (applies to all agents)\n\n" + "\n\n".join(parts) + "\n"


def roster(agents: dict, planned, naming: Naming) -> str:
    lines = ["# Team roster", "", "Call other agents by these exact names.", "",
             "| Agent name | Role | Use it for |", "|---|---|---|"]
    for agent_id, agent in agents.items():
        meta = agent["meta"]
        description = " ".join(str(meta["description"]).split())
        lines.append(f"| `{naming.ref(agent_id)}` | {meta['magenta']['title']} | {description} |")
    for agent_id in planned or []:
        lines.append(f"| `{naming.ref(agent_id)}` | (later phase, not available yet) | The human does this work for now. |")
    return "\n".join(lines) + "\n"


def instructions(root: Path, cfg: dict, agents: dict, agent_id: str, naming: Naming) -> str:
    """The full instructions of one agent: marker, constitution, roster, and the role body."""
    names = all_names(root, cfg)
    note = (f"<!-- {MARKER} from agents/{agent_id}.md. Do not edit this file. "
            "Edit the source and run: python3 magenta.py build -->\n\n")
    header = rewrite_names(constitution(root), names, naming) + "\n" + roster(agents, cfg.get("agents_planned"), naming)
    body = rewrite_names(agents[agent_id]["body"].strip(), names, naming)
    return note + header + "\n" + body + "\n"


def conductor_appendix(root: Path, cfg: dict, agents: dict, naming: Naming) -> str:
    """The constitution and the roster, added to the conductor skill at build time."""
    names = all_names(root, cfg)
    return ("\n\n" + rewrite_names(constitution(root), names, naming) + "\n"
            + roster(agents, cfg.get("agents_planned"), naming))


def write_rules(agent: dict) -> str:
    """Write rules as text, for tools that have no guard hook (Codex CLI, Gemini CLI)."""
    mg = agent["meta"]["magenta"]
    writes = "\n".join(f"- `{w}`" for w in mg.get("writes") or []) or "- (none)"
    shell = ", ".join(f"`{s}`" for s in mg.get("shell") or []) or "none"
    deny = ", ".join(f"`{s}`" for s in mg.get("shell_deny") or [])
    text = ("# Write and shell rules\n\n"
            "This tool does not run the Magenta guard. Follow these rules strictly.\n\n"
            "You may write only these paths. A path with `!` is denied. The last matching rule wins.\n\n"
            f"{writes}\n\nDo not write `.magenta/policy.json`, `.magenta/checks.lock`, `.magenta/verify-state.json`, "
            "`.magenta/active.json`, `acceptance.lock`, `.git/`, or secret files. Never approve checks.\n\n"
            f"Run only these shell commands: {shell}. Do not use shell operators such as `;`, `|`, or `>`.")
    if deny:
        text += f" Never run: {deny}."
    return text + " Do not push, merge, or deploy.\n\n"


def policy(agent_id: str, agent: dict) -> dict:
    mg = agent["meta"]["magenta"]
    return {"agent": agent_id, "writes": mg.get("writes") or [], "denies": mg.get("denies") or [],
            "shell": mg.get("shell") or [], "shell_deny": mg.get("shell_deny") or []}


def description(agent: dict) -> str:
    return " ".join(str(agent["meta"]["description"]).split())


def yaml_str(value) -> str:
    return json.dumps(value, ensure_ascii=False)


def skill_file(name: str, desc: str, body: str) -> str:
    return (f"---\nname: {name}\ndescription: {yaml_str(desc)}\n---\n"
            f"<!-- {MARKER}. Do not edit this file. -->\n\n{body.strip()}\n")


def canonical_skill(root: Path, name: str, naming: Naming, names) -> tuple[str, str]:
    meta, body = split_front_matter((root / "skills" / name / "SKILL.md").read_text(encoding="utf-8"))
    return " ".join(str(meta["description"]).split()), rewrite_names(body, names, naming)


def templates_body(root: Path) -> str:
    tdir = root / "templates"
    header = (tdir / "_header.md").read_text(encoding="utf-8").strip()
    handoff = (tdir / "_handoff.md").read_text(encoding="utf-8").strip()
    out = ["# Magenta artifact templates\n",
           "Copy the template. Replace each `<...>` placeholder. Delete the sections that do not apply, "
           "and write the reason in the handoff note.\n"]
    for path in sorted(tdir.iterdir()):
        if path.name.startswith("_") or not path.is_file():
            continue
        text = path.read_text(encoding="utf-8").replace("{{header}}", header).replace("{{handoff}}", handoff)
        lang = {".yaml": "yaml", ".json": "json"}.get(path.suffix, "markdown")
        out.append(f"## Template: {path.stem}\n\n````{lang}\n{text.strip()}\n````\n")
    return "\n".join(out)


def workflow_body(root: Path, naming: Naming, names) -> str:
    wdir = root / "workflows"
    files = [wdir / f"{n}.md" for n in WORKFLOW_ORDER if (wdir / f"{n}.md").exists()]
    files += [p for p in sorted(wdir.glob("*.md")) if p not in files]
    out = ["# Magenta workflows\n",
           "Start with the routing section: select the task type, the team, and the lane. Then follow the playbook "
           "of the task type. Feature tasks use the lanes lite, standard, and full.\n",
           "Gates for features: Gate 1 PRD go, Gate 2 scope and design, Gate 3 merge, Gate 4 release (full lane). "
           "Gates for other task types: plan gate and done gate. Only a human approves a gate.\n"]
    out += [rewrite_names(p.read_text(encoding="utf-8").strip(), names, naming) + "\n" for p in files]
    return "\n".join(out)
