class W10S6MetricsBadLinesTest(unittest.TestCase):
    VALID = {"workflow": "pr-review", "agent": "qa", "engine": "claude", "status": "OK",
             "cost_usd": 0.5, "turns": 3, "duration_s": 10}

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.home = Path(self.tmp.name).resolve() / "home"
        self.home.mkdir()

    def tearDown(self):
        self.tmp.cleanup()

    def metrics(self, lines) -> subprocess.CompletedProcess:
        repo = Path(self.tmp.name).resolve() / "repo"
        _write(repo / ".magenta" / "runs" / "runs.jsonl", "".join(line + "\n" for line in lines))
        return _cli(self.home, "metrics", repo)

    def assert_report(self, run: subprocess.CompletedProcess, total: str):
        self.assertEqual(run.returncode, 0, run.stdout + run.stderr)
        self.assertNotIn("Traceback", run.stderr)
        self.assertIn(f"Total cost of headless runs: {total} USD", run.stdout)

    def test_valid_json_that_is_not_an_object_is_skipped(self):
        for bad in ("[1, 2]", '"text"', "42", "null", "true"):
            with self.subTest(bad):
                run = self.metrics([json.dumps(self.VALID), bad])
                self.assert_report(run, "0.500")
                self.assertIn("Steps: 1", run.stdout)

    def test_non_numeric_cost_does_not_crash(self):
        for cost in ("abc", [1], {"usd": 1}):
            with self.subTest(cost=cost):
                bad = dict(self.VALID, cost_usd=cost)
                self.assert_report(self.metrics([json.dumps(self.VALID), json.dumps(bad)]), "0.500")

    def test_valid_lines_still_add_up(self):
        run = self.metrics([json.dumps(self.VALID), json.dumps(dict(self.VALID, cost_usd=0.25)), "not json"])
        self.assert_report(run, "0.750")
        self.assertIn("Steps: 2", run.stdout)


class W10S7LockOutsideRepoTest(unittest.TestCase):
    ITEM = "20261030-w10-demo"

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        base = Path(self.tmp.name).resolve()
        self.home = base / "home"
        self.home.mkdir()
        self.repo = base / "repo"
        self.work = self.repo / ".magenta" / "work" / self.ITEM
        _write(self.work / "acceptance" / "test_a.py", "def test_a():\n    assert True\n")
        _write(self.repo / "tests" / "test_bug.py", "def test_bug():\n    assert True\n")
        self.outside = base / "outside.txt"
        self.outside.write_text("outside\n", encoding="utf-8")

    def tearDown(self):
        self.tmp.cleanup()

    def lock(self, *files) -> subprocess.CompletedProcess:
        return _cli(self.home, "lock", self.repo, self.ITEM, "--files", *files)

    def test_file_outside_repository_fails_with_clear_error(self):
        for name in ("../outside.txt", str(self.outside)):
            with self.subTest(name):
                run = self.lock(name)
                output = run.stdout + run.stderr
                self.assertNotEqual(run.returncode, 0, output)
                self.assertNotIn("Traceback", output)
                self.assertIn("error", output.lower())
                self.assertIn("outside.txt", output)
                self.assertFalse((self.work / "acceptance.lock").exists())

    def test_file_inside_repository_is_still_locked(self):
        run = self.lock("tests/test_bug.py")
        self.assertEqual(run.returncode, 0, run.stdout + run.stderr)
        files = json.loads((self.work / "acceptance.lock").read_text(encoding="utf-8"))["files"]
        self.assertIn("tests/test_bug.py", files)
        self.assertIn(f".magenta/work/{self.ITEM}/acceptance/test_a.py", files)


