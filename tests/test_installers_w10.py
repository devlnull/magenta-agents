MAGENTA_ENV = ("MAGENTA_DIST", "MAGENTA_REPO", "MAGENTA_REF", "MAGENTA_HOME", "MAGENTA_TARGET")
NO_SHELL = shutil.which("sh") is None or shutil.which("git") is None or os.name == "nt"
NO_SHELL_REASON = "install.sh needs sh and git on macOS or Linux"


def _env(home: Path, **extra) -> dict:
    env = {k: v for k, v in os.environ.items() if k not in MAGENTA_ENV}
    env.update(HOME=str(home), USERPROFILE=str(home), XDG_CONFIG_HOME=str(home / ".config"),
               GIT_CONFIG_NOSYSTEM="1", GIT_ALLOW_PROTOCOL="file", GIT_TERMINAL_PROMPT="0",
               PYTHONUTF8="1", PYTHONDONTWRITEBYTECODE="1")
    env.update(extra)
    return env


def _cli(home: Path, *args, **extra) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(ROOT / "magenta.py"), *map(str, args)], cwd=str(home.parent),
                          capture_output=True, text=True, env=_env(home, **extra), timeout=120)


def _build_dist(dist_root: Path) -> Path:
    claude_code.build(ROOT, dist_root / "claude-code")
    return dist_root


def _install(home: Path, dist_root: Path) -> subprocess.CompletedProcess:
    return _cli(home, "install", "--home", home, "--python", sys.executable, MAGENTA_DIST=str(dist_root))


def _front_matter(path: Path) -> str:
    return path.read_text(encoding="utf-8").split("---\n")[1]


def _block_items(front_matter: str, key: str) -> list:
    lines = front_matter.splitlines()
    if f"{key}:" not in lines:
        return []
    start = lines.index(f"{key}:") + 1
    items = []
    for line in lines[start:]:
        if not line.startswith("  - "):
            break
        items.append(line[len("  - "):].strip())
    return items


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


class W10S1StaleInstallFilesTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory()
        base = Path(cls.tmp.name).resolve()
        new = _build_dist(base / "new")
        old = base / "old"
        shutil.copytree(new, old)
        old_dist = old / "claude-code"
        marker = f"<!-- {source.MARKER} from agents/retired.md. Do not edit this file. -->\n"
        _write(old_dist / "agents" / "magenta-retired.md", f"---\nname: magenta-retired\n---\n{marker}\n# Retired\n")
        _write(old_dist / "skills" / "magenta-retired" / "SKILL.md",
               f"---\nname: magenta-retired\ndescription: old\n---\n{marker}\n# Retired\n")
        _write(old_dist / "skills" / "magenta-legacy" / "SKILL.md",
               "---\nname: magenta-legacy\ndescription: old\n---\n# Legacy skill without the marker\n")
        cls.home = base / "home"
        cls.claude = cls.home / ".claude"
        cls.first = _install(cls.home, old)
        _write(cls.claude / "agents" / "magenta-ancient.md", f"---\nname: magenta-ancient\n---\n{marker}\n")
        cls.user_files = [cls.claude / "agents" / "my-agent.md", cls.claude / "agents" / "magenta-mine.md",
                          cls.claude / "skills" / "my-skill" / "SKILL.md",
                          cls.claude / "skills" / "magenta-mine" / "SKILL.md"]
        for path in cls.user_files:
            _write(path, "---\nname: mine\ndescription: my own file\n---\n# Mine\n")
        cls.second = _install(cls.home, new)

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def test_both_installs_succeed(self):
        for run in (self.first, self.second):
            self.assertEqual(run.returncode, 0, run.stdout + run.stderr)

    def test_previous_agent_with_marker_is_removed(self):
        self.assertFalse((self.claude / "agents" / "magenta-retired.md").exists())

    def test_previous_skill_with_marker_is_removed(self):
        self.assertFalse((self.claude / "skills" / "magenta-retired").exists())

    def test_previous_skill_in_manifest_without_marker_is_removed(self):
        self.assertFalse((self.claude / "skills" / "magenta-legacy").exists())

    def test_agent_with_marker_outside_manifest_is_removed(self):
        self.assertFalse((self.claude / "agents" / "magenta-ancient.md").exists())

    def test_user_files_without_marker_are_kept(self):
        for path in self.user_files:
            with self.subTest(path.relative_to(self.claude).as_posix()):
                self.assertTrue(path.exists())

    def test_current_agents_and_skills_are_installed(self):
        for rel in ("agents/magenta-qa.md", "agents/magenta-principal.md", "skills/magenta/SKILL.md",
                    "skills/magenta-templates/SKILL.md"):
            with self.subTest(rel):
                self.assertTrue((self.claude / rel).exists())


class W10S2ApostropheHomeTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory()
        base = Path(cls.tmp.name).resolve()
        cls.dist = _build_dist(base / "dist")
        cls.base = base
        source_meta = parse_yaml(_front_matter(ROOT / "skills" / "magenta" / "SKILL.md"))
        cls.token_items = [i for i in source_meta["allowed-tools"] if source.VERIFY_TOKEN in i]

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def install_into(self, name: str) -> Path:
        home = self.base / name
        run = _install(home, self.dist)
        self.assertEqual(run.returncode, 0, run.stdout + run.stderr)
        return home

    def assert_conductor_front_matter_is_valid(self, home: Path):
        skill = home / ".claude" / "skills" / "magenta"
        text = _front_matter(skill / "SKILL.md")
        meta = parse_yaml(text)
        script = (skill / "scripts" / "verify.py").as_posix()
        items = [i for i in meta["allowed-tools"] if "verify.py" in i]
        self.assertEqual(len(items), len(self.token_items), items)
        for item in items:
            self.assertIn(script, item)
            self.assertNotIn("${CLAUDE_SKILL_DIR}", item)
        for line in _block_items(text, "allowed-tools"):
            if line.startswith("'"):
                self.assertTrue(line.endswith("'") and len(line) > 1, line)
                self.assertNotIn("'", line[1:-1].replace("''", ""), f"a single quote is not doubled: {line}")
        if yaml is not None:
            self.assertEqual(yaml.safe_load(text)["allowed-tools"], meta["allowed-tools"])

    def test_conductor_front_matter_is_valid_yaml_with_apostrophe_in_home(self):
        self.assert_conductor_front_matter_is_valid(self.install_into("o'brien"))

    def test_conductor_front_matter_still_valid_with_plain_home(self):
        self.assert_conductor_front_matter_is_valid(self.install_into("plain"))

    def test_agent_hook_command_still_valid_with_apostrophe_in_home(self):
        home = self.install_into("o'neil")
        text = _front_matter(home / ".claude" / "agents" / "magenta-qa.md")
        command = parse_yaml(text)["hooks"]["PreToolUse"][0]["hooks"][0]["command"]
        self.assertIn((home / ".claude" / "magenta" / "guard.py").as_posix(), command)
        if yaml is not None:
            self.assertEqual(yaml.safe_load(text)["hooks"]["PreToolUse"][0]["hooks"][0]["command"], command)


@unittest.skipIf(NO_SHELL, NO_SHELL_REASON)
class W10S3InstallShRepoUpdateTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        base = Path(self.tmp.name).resolve()
        self.home = base / "home"
        self.home.mkdir()
        self.dir = base / "install"
        self.repo_a = self.make_repo(base / "a", "A")
        self.repo_b = self.make_repo(base / "b", "B")
        first = self.install_sh("--repo", self.repo_a.as_uri())
        self.assertEqual(first.returncode, 0, first.stdout + first.stderr)
        self.assertEqual(self.origin(), "A")

    def tearDown(self):
        self.tmp.cleanup()

    def git(self, repo: Path, *args):
        subprocess.run(["git", "-C", str(repo), "-c", "user.name=t", "-c", "user.email=t@example.com",
                        "-c", "commit.gpgsign=false", *args], check=True, capture_output=True,
                       env=_env(self.home), timeout=60)

    def make_repo(self, repo: Path, marker: str) -> Path:
        repo.mkdir()
        self.git(repo, "init", "-q")
        self.git(repo, "symbolic-ref", "HEAD", "refs/heads/main")
        self.commit(repo, marker)
        return repo

    def commit(self, repo: Path, marker: str):
        (repo / "magenta.py").write_text("import sys\nsys.exit(0)\n", encoding="utf-8")
        (repo / "origin.txt").write_text(marker + "\n", encoding="utf-8")
        self.git(repo, "add", "-A")
        self.git(repo, "commit", "-q", "-m", marker)

    def install_sh(self, *args, **extra) -> subprocess.CompletedProcess:
        return subprocess.run(["sh", str(ROOT / "install.sh"), "--dir", str(self.dir), "--ref", "main", *args],
                              cwd=str(self.home), capture_output=True, text=True, env=_env(self.home, **extra),
                              timeout=120)

    def origin(self) -> str:
        return (self.dir / "origin.txt").read_text(encoding="utf-8").strip()

    def test_update_uses_repo_option(self):
        run = self.install_sh("--repo", self.repo_b.as_uri())
        self.assertEqual(run.returncode, 0, run.stdout + run.stderr)
        self.assertEqual(self.origin(), "B")

    def test_update_uses_magenta_repo_variable(self):
        run = self.install_sh(MAGENTA_REPO=self.repo_b.as_uri())
        self.assertEqual(run.returncode, 0, run.stdout + run.stderr)
        self.assertEqual(self.origin(), "B")

    def test_update_without_repo_value_still_uses_existing_origin(self):
        self.commit(self.repo_a, "A2")
        run = self.install_sh()
        self.assertEqual(run.returncode, 0, run.stdout + run.stderr)
        self.assertEqual(self.origin(), "A2")


